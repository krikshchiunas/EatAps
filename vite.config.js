import { defineConfig, loadEnv } from 'vite'
import react from '@vitejs/plugin-react'
import { readFileSync } from 'node:fs'

// Версия приложения — из package.json, а не переписанная руками во втором
// месте: две версии рано или поздно разъезжаются, и «О приложении» начинает
// врать. Показывает её экран About.
const pkg = JSON.parse(readFileSync(new URL('./package.json', import.meta.url), 'utf8'))

export default defineConfig(({ mode }) => {
  // ⚠ Файлы .env Vite читает САМ и в process.env их НЕ кладёт. Поэтому здесь
  // нужен loadEnv: без него переменная, заданная в .env.local, осталась бы
  // невидимой для define, а в коде (через import.meta.env) была бы видна —
  // и два признака «Web3 включён» разошлись бы. Кнопка рисовалась бы, а
  // компонент под ней оказался бы null: падение прямо в форме входа.
  //
  // Третий аргумент '' — читать все переменные, а не только с префиксом VITE_,
  // чтобы поведение не зависело от того, как её назвали в окружении Vercel.
  const env = loadEnv(mode, process.cwd(), '')

  return {
    define: {
      __APP_VERSION__: JSON.stringify(pkg.version),
      // Включён ли вход по кошельку. Именно КОНСТАНТА, а не вычисление из
      // import.meta.env в коде: Rollup сворачивает ветку и выбрасывает
      // динамический импорт только тогда, когда условие является литералом
      // прямо в месте ветвления. Через `Boolean(projectId)` в соседнем модуле
      // он этого не видит, и чанк на 2,7 МБ собирался даже при выключенной
      // функции — лежал в артефактах и ругался на размер при каждой сборке.
      __WEB3_ENABLED__: JSON.stringify(Boolean(env.VITE_WALLETCONNECT_PROJECT_ID)),
    },
    plugins: [react()],
    build: {
      rollupOptions: {
        output: {
          // Крупные и РЕДКО МЕНЯЮЩИЕСЯ куски выносим в свои файлы. Смысл не
          // только в размере первой загрузки: у отдельного чанка свой хэш, и
          // правка компонента больше не сбрасывает у людей кэш справочника
          // продуктов на полтора мегабайта.
          manualChunks: {
            // React и клиент Supabase меняются только при обновлении зависимостей.
            vendor: ['react', 'react-dom', '@supabase/supabase-js'],
            // Справочник продуктов сюда НЕ добавлен — и это осознанно.
            //
            // Он нужен только экрану добавления еды и сканеру, оба ленивые, и
            // Rollup сам выносит его в отдельный чанк по факту динамического
            // импорта. А запись в manualChunks делает чанк ВЕРХНЕУРОВНЕВЫМ, и
            // Vite добавляет на него <link rel="modulepreload"> — то есть
            // справочник снова качается при старте, просто с низким приоритетом.
            // Проверено измерением: с группой 75 КБ уезжали в стартовую загрузку,
            // без неё — не уезжают вовсе.
          },
        },
      },
      // Порог предупреждения оставляем стандартным: он должен срабатывать,
      // если главный чанк снова начнёт расти.
      chunkSizeWarningLimit: 500,
    },
    server: {
      host: true,
      port: 5173,
    },
  }
})
