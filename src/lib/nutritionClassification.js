// Возвращает DIAAS-ориентир источника белка (0..1.2) или null, если продукт не
// удалось отнести ни к одной категории.
export function estimateProteinQuality(food) {
  const protein = Number(food?.protein)
  if (!Number.isFinite(protein) || protein <= 0) return { diaas: null, confidence: 'unknown' }
  const n = nrm(food?.name)
  for (const [words, diaas] of PROTEIN_DIAAS_NAME_OVERRIDES) {
    if (anyOf(n, words)) return { diaas, confidence: 'estimated' }
  }
  const byCat = PROTEIN_DIAAS_BY_CAT[food?.cat || inferCategory(food)]
  if (byCat != null) return { diaas: byCat, confidence: 'estimated' }
  return { diaas: null, confidence: 'unknown' }
}

// Доля белка продукта, которая идёт в зачёт «качественного белка».
// Усечение на 1 — рекомендация FAO для смешанного рациона.
export const usableProteinShare = (diaas) => (diaas == null ? null : Math.min(1, Math.max(0, diaas)))

