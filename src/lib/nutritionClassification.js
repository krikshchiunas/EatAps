// Слова, которые в определённом окружении означают не то, что обычно:
// «кокосовое молоко» — напиток из ореха, «арахисовая паста» — не макароны.
const CONTEXT_SKIPS = [
  [/(кокос|овсян|миндал|соев|рисов|растительн|орехов|гречнев)\S*\s+(молок|напит)/, /^(молок|напит)/],
  [/(арахис|миндал|орех|томат|кунжут|шокол|фисташ|кешью|тыкв|зубн|кедров)\S*\s+паст/, /^паст/],
]

function wordMatches(word, stem) {
  return stem instanceof RegExp ? stem.test(word) : word.startsWith(stem)
}

// Профили, которые называет само название. Пустой массив — название ничего не
// говорит о белке.
function profilesFromName(name) {
  const n = nrm(name)
  if (!n) return []
  const skips = CONTEXT_SKIPS.filter(([ctx]) => ctx.test(n)).map(([, word]) => word)
  const words = n.split(/[^a-zа-яäöüß0-9-]+/).filter(Boolean)
    .flatMap((w) => (w.includes('-') ? [w, ...w.split('-')] : [w]))
  const found = []
  const generic = []
  let dish = false
  for (const w of words) {
    if (skips.some((re) => re.test(w))) continue
    const rule = WORD_RULES.find((r) => r.stems.some((s) => wordMatches(w, s)))
    if (!rule) continue
    if (rule.kind === 'dish') { dish = true; continue }
    const into = rule.kind === 'generic' ? generic : found
    for (const p of rule.profiles) if (!into.includes(p)) into.push(p)
  }
  // «Протеин» без указания источника — сывороточный; с источником — он сам.
  if (found.length === 0 && generic.length) found.push(generic[0])
  // «Бутерброд» без начинки в названии — смешанное блюдо; с начинкой — хлеб и она.
  if (dish) {
    if (found.length === 0) found.push('mixed')
    else if (!found.includes('wheat') && !found.includes('wholegrain')) found.push('wheat')
  }
  return found
}

// Смешивание компонентов блюда, известного только по названию: считаем, что
// по весу их примерно поровну, и потому белок делится пропорционально
// типичной белковости каждого.
function blendByDensity(keys) {
  const total = keys.reduce((a, k) => a + PROTEIN_PROFILES[k].density, 0)
  return keys.map((k) => ({ key: k, share: PROTEIN_PROFILES[k].density / total }))
}

// Разложение белка записи по профилям: [{ key, share }], доли в сумме 1.
// Порядок источников: явный состав (proteinMix — его пишет конструктор
// бутербродов и рецепты) → название → категория. null — определить нельзя.
export function proteinPartsOf(food) {
  const mix = food?.proteinMix
  if (mix && typeof mix === 'object') {
    const entries = Object.entries(mix).filter(([k, v]) => PROTEIN_PROFILES[k] && Number(v) > 0)
    const sum = entries.reduce((a, [, v]) => a + Number(v), 0)
    if (sum > 0) return entries.map(([key, v]) => ({ key, share: Number(v) / sum }))
  }
  const byName = profilesFromName(food?.name)
  if (byName.length) return blendByDensity(byName)
  const byCat = PROFILE_BY_CAT[food?.cat]
  if (byCat) return [{ key: byCat, share: 1 }]
  return null
}

// Сводка по смеси белков. grams — { профиль: граммы белка }.
// Возвращает долю усвояемого белка (0..1), DIAAS смеси без усечения и
// лимитирующую аминокислоту.
export function mixProteinQuality(grams) {
  let total = 0
  let absorbed = 0
  const digestibleAA = Object.fromEntries(AA_KEYS.map((k) => [k, 0]))
  for (const [key, g] of Object.entries(grams || {})) {
    const p = PROTEIN_PROFILES[key]
    const v = Number(g)
    if (!p || !(v > 0)) continue
    total += v
    absorbed += v * p.dig
    for (const k of AA_KEYS) digestibleAA[k] += v * p.aa[k] * p.dig
  }
  if (!(total > 0)) return null
  let diaas = Infinity
  let limiting = null
  for (const k of AA_KEYS) {
    const score = digestibleAA[k] / (total * AA_REF[k])
    if (score < diaas) { diaas = score; limiting = k }
  }
  const digestibility = absorbed / total
  return { diaas, digestibility, limiting, usable: Math.max(0, Math.min(diaas, digestibility)) }
}

// Качество белка одной записи. diaas — показатель без усечения (нужен для
// подсказок: 0 у желатина, низкий у круп), usable — доля, которая реально
// пойдёт в дело (≤ усвояемости). null, если продукт опознать не удалось.
export function estimateProteinQuality(food) {
  const protein = Number(food?.protein)
  if (!Number.isFinite(protein) || protein <= 0) return { diaas: null, usable: null, confidence: 'unknown' }
  const parts = proteinPartsOf(food)
  if (!parts) return { diaas: null, usable: null, confidence: 'unknown' }
  const q = mixProteinQuality(Object.fromEntries(parts.map((p) => [p.key, p.share])))
  return {
    diaas: Math.round(q.diaas * 100) / 100,
    usable: Math.round(q.usable * 1000) / 1000,
    digestibility: Math.round(q.digestibility * 100) / 100,
    limiting: q.limiting,
    profiles: parts.map((p) => p.key),
    confidence: 'estimated',
  }
}

// Порог, ниже которого источник белка считается заведомо неполноценным
// (растительный монобелок, желатин): нужен подсказкам, а не расчёту.
export const PROTEIN_QUALITY_LOW = 0.6

// Состав белка блюда, собранного из известных компонентов (конструктор,
// рецепт): { профиль: граммы белка }. Хранится в записи как proteinMix, чтобы
// «Бутерброд» из конструктора считался как хлеб + салями + сыр, а не как
// безликое «блюдо». Компонент, который не удалось опознать, считаем овощным —
// он почти всегда и есть зелень, соус или фрукт с граммом белка.
export function proteinMixOf(components) {
  const mix = {}
  for (const c of components || []) {
    const protein = Number(c?.protein)
    if (!(protein > 0)) continue
    const parts = proteinPartsOf(c) || [{ key: 'veg', share: 1 }]
    for (const { key, share } of parts) mix[key] = (mix[key] || 0) + protein * share
  }
  const keys = Object.keys(mix)
  if (!keys.length) return null
  return Object.fromEntries(keys.map((k) => [k, Math.round(mix[k] * 100) / 100]))
}
