const cache = new Map()
const CACHE_LIMIT = 4000

const toRef = (key, sugarFree) => {
  const [kcal, carbs, sugar, fiber, natural] = REF[key]
  // Без сахара — минус добавленный сахар и в углеводах, и в калориях: иначе
  // «Coca-Cola Zero» сравнивалась бы с углеводами обычной колы.
  const added = sugarFree ? sugar - natural : 0
  return Object.freeze({
    key,
    kcal: kcal - 4 * added,
    carbs: carbs - added,
    fiber,
    // «Без сахара» убирает добавленный сахар, но не лактозу: в сгущёнке без
    // сахара и в шоколаде без сахара молочный сахар остаётся.
    sugar: sugarFree ? natural : sugar,
    natural,
    // Сухофрукты и овощи сушат и вялят: их натуральный сахар сравнивается и по
    // калориям, а не только по весу (см. nutrition.js).
    plant: /^(apple|pear|banana|citrus|grape|stoneFruit|berry|melon|pineapple|mango|kiwi|persimmon|pomegranate|fruit|carrot|beet|tomato|pepper|pumpkin|corn|veg)$/.test(key),
  })
}

// Профиль записи: { key, kcal, carbs, sugar, fiber, natural } на 100 г.
// Никогда не null — в худшем случае «смешанная еда» (generic).
export function carbRefFor(food) {
  const name = String(food?.name || '')
  const cat = food?.cat || ''
  const cacheKey = `${name}\u0001${cat}`
  const hit = cache.get(cacheKey)
  if (hit) return hit

  const tokens = nameTokens(name)
  const sugarFree = SUGAR_FREE.some((s) => stemHit(tokens, s))
  let key = null
  if (tokens.words.length) {
    for (const [refKey, stems] of RULES) {
      if (COMPOSITE_CATS.has(cat) && INGREDIENT_ONLY.has(refKey)) continue
      if (stems.some((s) => stemHit(tokens, s))) { key = refKey; break }
    }
  }
  if (!key) {
    const c = cat || categoryFromName(name)
    key = (c && BY_CAT[c]) || 'generic'
  }
  const ref = toRef(key, sugarFree)
  if (cache.size >= CACHE_LIMIT) cache.clear()
  cache.set(cacheKey, ref)
  return ref
}

