// ─────────────────────────────────────────────────────────────────────────────
// Публичный ID — короткий код, который человек отправляет другу, чтобы тот его
// добавил. Единственное, что по нему можно сделать, — найти UUID владельца
// (RPC find_user_by_public_id) и отправить заявку в друзья.
//
// Раньше ID выдавались подряд: AA000001, AA000002, AA000003… Это означало, что
// перебор от AA000001 находит ВСЕХ зарегистрированных пользователей за столько
// запросов, сколько их в базе. Читать чужие данные это не давало — RLS не
// пускает, — но давало список всех аккаунтов и возможность завалить каждого
// заявками. Ограничение частоты заявок (миграция hardening) било по следствию,
// а не по причине.
//
// Теперь ID выдаётся случайно из 32-символьного алфавита длиной 12 символов:
// 32^12 ≈ 1.15·10^18 ≈ 2^60 вариантов. Перебор перестаёт быть способом узнать
// хоть что-нибудь: на 10 пользователей вероятность попадания с одной попытки
// около 10^-17.
//
// Алфавит — крокфордов base32: цифры и заглавные латинские буквы без I, L, O
// (неотличимы от 1 и 0 в рукописном и при чтении вслух) и без U (чтобы код
// случайно не сложился в непристойность). Ввод сворачивается к алфавиту:
// написанный человеком «O» примем за ноль, «I» и «l» — за единицу.
// ─────────────────────────────────────────────────────────────────────────────

export const PUBLIC_ID_ALPHABET = '0123456789ABCDEFGHJKMNPQRSTVWXYZ'
export const PUBLIC_ID_LENGTH = 12

// Тот же набор, что и в PUBLIC_ID_ALPHABET, диапазонами: 0-9, A-H, J, K, M, N,
// P-T, V-Z. Пропущены ровно I, L, O, U.
export const PUBLIC_ID_RE = /^[0-9A-HJKMNP-TV-Z]{12}$/

// Привести пользовательский ввод к каноническому виду.
// Возвращает 12 символов в верхнем регистре либо null, если это не публичный ID.
// Разделители, пробелы и регистр значения не имеют: и «7k4m-9xpq-2rtv», и
// «7K4M 9XPQ 2RTV», и «7K4M9XPQ2RTV» — один и тот же код.
export function normalizePublicId(raw) {
  if (typeof raw !== 'string') return null
  const cleaned = raw.toUpperCase().replace(/[^0-9A-Z]/g, '')
  // Крокфордова свёртка неоднозначных букв. U не сворачиваем: он не входит в
  // алфавит вовсе, и код с ним — просто опечатка, которую честнее отклонить.
  const folded = cleaned.replace(/[IL]/g, '1').replace(/O/g, '0')
  return PUBLIC_ID_RE.test(folded) ? folded : null
}

export function isPublicId(raw) {
  return normalizePublicId(raw) !== null
}

// Вид для показа и копирования: XXXX-XXXX-XXXX. Группы по четыре читаются вслух
// и перенабираются заметно надёжнее, чем сплошные двенадцать символов.
// В базе хранится канонический вид без дефисов — форматирование живёт только
// на экране.
export function formatPublicId(id) {
  const norm = normalizePublicId(id)
  if (!norm) return typeof id === 'string' ? id : ''
  return norm.replace(/(.{4})(?=.)/g, '$1-')
}
