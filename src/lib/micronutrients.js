// пьют добавки (креатин, омега-3, коллаген, адаптогены).
//
// Здесь ТОЛЬКО определения: что это, в чём измеряется, сколько нужно в день и
// с какого количества начинается перебор. Ни расчётов по еде (foodMicros.js),
// ни каталога банок (supplements.js), ни суммирования дня (microSummary.js) —
// иначе таблица норм расползётся по трём файлам и разъедется.
//
// ВАЖНО ПРО СМЫСЛ ЧИСЕЛ. Норма (rda) — это справочный ориентир для взрослого
// (RDA/AI из DRI, EFSA и МР 2.3.1.2432-08), а НЕ назначение. Верхний предел
// (ul) — это UL, «столько долго получать не стоит», а не «доза яда». Приложение
// показывает их как ориентиры и нигде не называет диагнозом или лечением.
//
// ─────────────────────────────────────────────────────────────────────────────
// Три вещи, на которых легко ошибиться и из-за которых пришлось бы всё
// переделывать, поэтому они заложены в модель с самого начала:
//
//   1. ЕДИНИЦА У КАЖДОГО КЛЮЧА СВОЯ И НЕИЗМЕННАЯ. Витамин C везде в мг, B12 —
//      в мкг, креатин — в граммах. Всё приложение (еда, добавки, цели, суммы)
//      считает в этой базовой единице ключа. Пересчёт мкг↔мг живёт только в
//      каталоге добавок, где на этикетке может быть написано что угодно.
//
//   2. НЕ ВСЕ ПОКАЗАТЕЛИ — ЦЕЛИ. Натрий и кофеин надо не «набрать», а не
//      превысить. Поэтому у определения есть kind: 'target' (добираем) или
//      'limit' (держимся ниже). Рисовать натрий полоской «40% нормы, добери
//      ещё» — вредный совет, а не недочёт оформления.
//
//   3. ВЕРХНИЙ ПРЕДЕЛ ИНОГДА ОТНОСИТСЯ ТОЛЬКО К ДОБАВКАМ. UL магния (350 мг),
//      ниацина (35 мг) и фолиевой кислоты (1000 мкг) установлен для
//      синтетической формы из таблеток: магнием из гречки и зелени превысить
//      его невозможно, и предупреждать об этом — врать. Такие пределы помечены
//      ulScope: 'supp' и считаются только от добавок.
// ─────────────────────────────────────────────────────────────────────────────

