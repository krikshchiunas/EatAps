// ── Нормы под конкретного человека ───────────────────────────────────────────
// Пол и возраст меняют норму заметно: железа женщине до 50 нужно 18 мг, а
// мужчине 8 — показывать обоим одну полоску значило бы обмануть и того, и
// другого. Профиля может не быть вовсе (гость, не прошёл анкету) — тогда берём
// мужские значения как более высокие: занижать норму опаснее, чем завышать.

const SEX = (profile) => (profile?.sex === 'female' ? 'female' : 'male')

export function rdaFor(def, profile) {
  if (!def?.rda) return null
  const sex = SEX(profile)
  let value = def.rda[sex]
  const age = Number(profile?.age)
  if (def.ageRda && Number.isFinite(age)) {
    // Уточнения отсортированы по возрасту: применяем все подходящие по
    // возрастанию, поэтому побеждает самое старшее подходящее.
    for (const step of [...def.ageRda].sort((a, b) => a.from - b.from)) {
      if (age >= step.from && step[sex] != null) value = step[sex]
    }
  }
  return value ?? null
}

// Порог, выше которого количество называется перебором.
//
// Тонкость, без которой счётчик превращается в паникёра. Превышение СПРАВОЧНОЙ
// нормы само по себе не новость: 50 мкг витамина D — это три с половиной нормы
// и совершенно обычная капсула, до верхнего предела там ещё вдвое. А вот
// превышение цели, которую человек поставил себе сам, — новость всегда: он
// назвал своё число, и выходить за него он не собирался.
//
// Поэтому:
//   • личная цель  → перебор начинается с полутора целей;
//   • справочная норма при известном верхнем пределе → перебор начинается там,
//     где до предела остаётся треть;
//   • справочная норма без предела → перебор с трёх норм.
export const OVER_RATIO = 1.5
const UL_APPROACH = 0.7
const NO_UL_RATIO = 3

export function overThreshold(def, target, personal) {
  if (!(target > 0)) return null
  if (personal) return target * OVER_RATIO
  if (def?.ul != null) return Math.max(target * OVER_RATIO, def.ul * UL_APPROACH)
  return target * NO_UL_RATIO
}

// Полная карта «ключ → цель» для человека, с учётом его личных правок.
// overrides — то, что человек задал руками (prefs.microGoals): «мне нужно 500
// витамина C». Это его решение, и оно сильнее справочной нормы.
export function microTargets(profile, overrides = {}) {
  const out = {}
  for (const def of MICRONUTRIENTS) {
    const custom = Number(overrides?.[def.key])
    const target = Number.isFinite(custom) && custom > 0 ? custom : rdaFor(def, profile)
    if (target != null) out[def.key] = target
  }
  return out
}

// Проверка личной цели перед сохранением. Пустая строка — «убрать мою цель и
// вернуть справочную норму», а не ноль: цель «ноль витамина C» бессмысленна.
// Верхняя граница — десять UL (или тысяча норм): защита от опечатки в разряде,
// а не запрет на высокие дозы.
export function sanitizeMicroGoal(key, raw) {
  const def = microDef(key)
  if (!def) return null
  if (raw == null || raw === '') return null
  const n = Number(String(raw).replace(',', '.'))
  if (!Number.isFinite(n) || n <= 0) return null
  const ceiling = def.ul != null ? def.ul * 10 : (def.rda?.male || 100) * 1000
  if (n > ceiling) return null
  return Math.round(n * 1000) / 1000
}

// ── Форматирование ───────────────────────────────────────────────────────────
// Микронутриенты живут в разных порядках величин: 2,4 мкг B12 и 3400 мг калия.
// Единое правило: до 10 — одна-две значащие цифры после запятой, дальше целое.
// Печатаем через запятую — по-русски разделитель именно такой.

export function formatMicro(value, unit) {
  // null и пустая строка — это «неизвестно», а Number(null) даёт ноль. Без
  // этой проверки неизвестное значение печаталось бы как измеренный «0 мг» —
  // ровно та подмена, из-за которой в дневнике когда-то стояло честное на вид
  // «Б0 У0 Ж0» у продуктов без данных.
  if (value == null || value === '') return '—'
  const n = Number(value)
  if (!Number.isFinite(n)) return '—'
  const abs = Math.abs(n)
  const digits = abs >= 10 ? 0 : abs >= 1 ? 1 : 2
  const fixed = n.toFixed(digits)
  // Хвостовые нули убираем только у дробной части: «0,90 мг» и «2,0 мкг» —
  // это шум, а «100» ронять до «1» нельзя.
  const text = fixed.includes('.') ? fixed.replace(/0+$/, '').replace(/\.$/, '') : fixed
  const ru = text.replace('.', ',')
  return unit ? `${ru} ${unit}` : ru
}
