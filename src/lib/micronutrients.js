// ─────────────────────────────────────────────────────────────────────────────
// Определения.
//
//   key       — идентификатор, по нему всё считается и хранится;
//   label     — как называется на экране;
//   short     — короткое имя для тесных мест (плитки, чипы);
//   unit      — БАЗОВАЯ единица ключа: 'мг' | 'мкг' | 'г' | 'млрд КОЕ';
//   group     — группа из MICRO_GROUPS;
//   kind      — 'target' (норму добираем) | 'limit' (держимся ниже);
//   rda       — { male, female } справочная норма (для kind:'limit' — ориентир
//               «столько уже много», см. ниже поле limit);
//   ageRda    — [{ from, male?, female? }] возрастные уточнения (от N лет);
//   ul        — верхний предел, null если не установлен;
//   ulScope   — 'all' (считаем всё) | 'supp' (предел только для добавок);
//   fromFood  — правда ли вещество реально приходит с едой. Ашваганда и
//               мелатонин в еде не считаются: у них не бывает «набрал из
//               продуктов», и рисовать им вклад еды значило бы врать;
//   optional  — показывать только если человек это принимает или получил с
//               едой. Иначе экран дня превратился бы в список из 70 полосок,
//               где 40 всегда пустые;
//   about     — одна фраза, зачем это, для пояснения в интерфейсе.
// ─────────────────────────────────────────────────────────────────────────────

const D = (key, label, unit, group, rest = {}) => ({
  key,
  label,
  short: rest.short || label,
  unit,
  group,
  kind: rest.kind || 'target',
  rda: rest.rda ?? null,
  ageRda: rest.ageRda || null,
  ul: rest.ul ?? null,
  ulScope: rest.ulScope || 'all',
  fromFood: rest.fromFood !== false,
  optional: rest.optional === true,
  about: rest.about || '',
})

