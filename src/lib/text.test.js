import { test } from 'node:test'
import assert from 'node:assert/strict'
import { plural } from './text.js'

test('склонение по числу — одно правило на всё приложение', () => {
  const p = (n) => plural(n, 'продукт', 'продукта', 'продуктов')
  assert.deepEqual([1, 2, 4, 5, 11, 12, 21, 22, 25, 101, 111].map(p), [
    'продукт', 'продукта', 'продукта', 'продуктов',
    'продуктов', 'продуктов', 'продукт', 'продукта', 'продуктов',
    'продукт', 'продуктов',
  ])
})
