// Признак «Web3-вход включён» — отдельно от самого AppKit и намеренно без
// единого импорта из него.
//
// Форме входа нужно знать только, показывать ли кнопку кошелька. Раньше она
// спрашивала об этом appkit.js, а тот тянет @reown/appkit со всеми адаптерами —
// почти 2.7 МБ, которые уезжали в чанк формы входа и грузились у каждого, кто
// просто открыл «Войти», даже если кошельком он никогда не пользовался.
// Проверка переменной окружения стоит ноль, поэтому живёт здесь.
const projectId = import.meta.env.VITE_WALLETCONNECT_PROJECT_ID || ''

export const WALLETCONNECT_PROJECT_ID = projectId
// Тот же признак, что и константа сборки __WEB3_ENABLED__ (см. vite.config.js).
// Здесь он нужен для условий в разметке, там — чтобы Rollup мог выбросить
// импорт. Считаются оба из одной переменной окружения, разойтись не могут.
export const web3Enabled = Boolean(projectId)
