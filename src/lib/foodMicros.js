// ─────────────────────────────────────────────────────────────────────────────
// Микронутриенты ЕДЫ: сколько витаминов, минералов и прочего приходит с каждой
// съеденной порцией.
//
// Зачем это вообще. Без еды счётчик добавок врёт в самую опасную сторону:
// человек видит «витамина C сегодня 300 из 500, добери» — а он уже съел
// килограмм перца и апельсинов и давно за нормой. Или наоборот: пьёт креатин,
// хотя в его дне 400 г говядины, где креатина и так почти два грамма.
//
// ── Как устроено ────────────────────────────────────────────────────────────
// Держать таблицу микронутриентов на каждый из тысячи продуктов базы
// невозможно и не нужно: содержание витаминов в «курице» и «куриной грудке
// гриль» отличается меньше, чем между двумя пачками одного бренда. Поэтому
// продукт сопоставляется с ПРОФИЛЕМ — типовым представителем своей группы, у
// которого прописан состав на 100 г (значения справочные, порядка USDA
// FoodData Central и таблиц Скурихина).
//
// Сопоставление в три ступени, от точного к грубому:
//   1. по названию (см. правила совпадения ниже);
//   2. по категории продукта (cat: 'fish' → усреднённый профиль рыбы);
//   3. никак — тогда продукт помечается unknown и НЕ считается нулём.
//
// Третья ступень — принципиальная. Неопознанный продукт не должен молча
// добавлять ноль: иначе день из сплошных сканированных штрихкодов покажет
// «витаминов 0», и человек побежит пить лишнюю банку. Мы честно говорим, какая
// доля дня осталась неразобранной.
//
// ── Чего эта модель НЕ делает ───────────────────────────────────────────────
// Не учитывает усвоение. Железо из говядины усваивается в разы лучше, чем из
// гречки, кальций хуже усваивается вместе с фитатами, каротин из моркови
// зависит от жира в тарелке. Всё это — про биодоступность, и обещать такую
// точность было бы враньём. Здесь считается СОДЕРЖАНИЕ в съеденном, и на
// экране это названо ориентиром, а не медицинским показателем.
// ─────────────────────────────────────────────────────────────────────────────

const nrm = (s) => String(s || '').toLowerCase().replace(/ё/g, 'е')

// Слова названия. Разбиваем по всему, что не буква и не цифра: «Гречка,
// варёная» и «гречка(варёная)» должны дать одинаковые слова.
const wordsOf = (name) => nrm(name).split(/[^0-9a-zа-я%]+/).filter(Boolean)

