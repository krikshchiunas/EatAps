// ── Сопоставление продукта с профилем ────────────────────────────────────────

function stemHit(words, norm, stem) {
  if (stem.startsWith('=')) return words.includes(stem.slice(1))
  if (stem.includes(' ')) return norm.includes(stem)
  // Начало слова, а не подстрока: иначе «шоКОЛАд» попадал бы в «колу»,
  // а «суХАРики» — в «сухофрукты».
  return words.some((w) => w.startsWith(stem))
}

export function microProfileFor(food) {
  const norm = nrm(food?.name)
  const words = wordsOf(food?.name)
  if (words.length) {
    for (const [id, stems, per100] of PROFILES) {
      if (stems.some((s) => stemHit(words, norm, s))) {
        return { id, per100, confidence: 'estimated' }
      }
    }
  }
  const cat = food?.cat
  if (cat && BY_CAT[cat]) return { id: 'cat:' + cat, per100: BY_CAT[cat], confidence: 'category' }
  return null
}

// ── Масса порции ─────────────────────────────────────────────────────────────
// grams у записи дневника означает разное в зависимости от unit: для «г» это
// граммы, для «мл» — миллилитры, а для «порция» — ЧИСЛО ПОРЦИЙ (так пишет
// конструктор рецептов). Умножить содержание на «2 порции» как на два грамма —
// ошибка в пятьдесят раз, поэтому масса берётся только там, где она правда масса.
//
// Миллилитры считаем за граммы: для воды, молока, сока и кофе расхождение
// (1.00–1.05 г/мл) меньше, чем разброс самих справочных значений.
export function massOf(entry) {
  const unit = entry?.unit || 'г'
  if (unit !== 'г' && unit !== 'мл') return null
  const n = Number(entry?.grams)
  return Number.isFinite(n) && n > 0 ? n : null
}

// ── Микронутриенты одной записи дневника ─────────────────────────────────────
// Возвращает { values, confidence }:
//   values     — { ключ: количество в базовой единице ключа } для этой порции;
//   confidence — 'estimated' (нашли профиль по названию),
//                'category'  (только по категории),
//                'unknown'   (не опознали ИЛИ не знаем массу порции).
//
// 'unknown' — не то же самое, что «ноль»: см. шапку файла.
export function microsForEntry(entry) {
  const mass = massOf(entry)
  if (mass == null) return { values: {}, confidence: 'unknown' }
  const profile = microProfileFor(entry)
  if (!profile) return { values: {}, confidence: 'unknown' }
  const k = mass / 100
  const values = {}
  for (const key in profile.per100) {
    const v = profile.per100[key] * k
    if (v > 0) values[key] = v
  }
  return { values, confidence: profile.confidence, profileId: profile.id }
}

// Сумма по всем записям дня.
//
// covered / total — сколько записей удалось разобрать. Это не украшение:
// именно по ним экран решает, показывать ли «часть продуктов не опознана».
// Считаем ВСЕ записи, включая те, у которых неизвестна масса, — иначе доля
// разобранного выглядела бы лучше, чем есть.
export function sumFoodMicros(entries = []) {
  const values = {}
  let covered = 0
  let byCategory = 0
  let total = 0
  // Значение по умолчанию подставляется только вместо undefined, а null сюда
  // приходит легко: день без ключа supps/meals в старом кэше. Без этой проверки
  // цикл бросал бы прямо при отрисовке экрана дня.
  for (const e of Array.isArray(entries) ? entries : []) {
    if (!e || !e.name) continue
    total += 1
    const { values: v, confidence } = microsForEntry(e)
    if (confidence === 'unknown') continue
    if (confidence === 'category') byCategory += 1
    covered += 1
    for (const key in v) values[key] = (values[key] || 0) + v[key]
  }
  return { values, covered, byCategory, total }
}

// Кем именно набран нутриент за день — для подсказки «откуда взялось».
// Возвращает до `limit` продуктов с наибольшим вкладом в конкретный ключ.
export function topSourcesFor(entries = [], key, limit = 3) {
  const rows = []
  for (const e of Array.isArray(entries) ? entries : []) {
    if (!e || !e.name) continue
    const { values } = microsForEntry(e)
    const v = values[key]
    if (v > 0) rows.push({ name: e.name, emoji: e.emoji || '🍽️', value: v })
  }
  return rows.sort((a, b) => b.value - a.value).slice(0, limit)
}
