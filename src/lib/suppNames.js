// ─────────────────────────────────────────────────────────────────────────────
// Добавки на языке интерфейса.
//
// В дневнике и стеке у каталожной добавки хранится suppId и исходное имя —
// как у продуктов, переводится только показ. По suppId перевод находится
// всегда, даже если имя в каталоге потом поправят. Своя добавка человека
// (suppId нет) показывается так, как он её назвал.
// ─────────────────────────────────────────────────────────────────────────────
import { dataTable } from './i18n.js'

const row = (x) => {
  const id = x?.suppId ?? x?.id
  return id ? dataTable('supps')?.[id] : null
}

export const suppName = (x) => row(x)?.name ?? x?.name ?? ''
export const suppNote = (x) => row(x)?.note ?? x?.note ?? ''
export const suppWarn = (x) => row(x)?.warn ?? x?.warn ?? ''
