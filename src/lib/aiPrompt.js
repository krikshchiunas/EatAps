export const DEFAULT_TONE = 'calm'

// Тон и согласие живут в prefs — синхронизируются между устройствами вместе с
// остальными настройками. Версия согласия отдельно: если текст предупреждения
// поменяется по сути, поднимаем её, и человек подтверждает заново.
export const TONE_PREF = 'aiTone'
export const TONE_CONSENT_PREF = 'aiToneConsent' // { version, at }
export const TONE_CONSENT_VERSION = 1

export function toneById(id) {
  return TONES[id] || TONES[DEFAULT_TONE]
}

export function hasToneConsent(prefs) {
  const c = prefs?.[TONE_CONSENT_PREF]
  return !!c && c.version === TONE_CONSENT_VERSION
}

// Единственный источник правды о том, каким тоном говорить прямо сейчас.
// Тон с опт-ином без действующего согласия молча падает на спокойный: так
// протухшее согласие или сброшенные данные не оставят включённым мат.
export function resolveTone(prefs) {
  const t = toneById(prefs?.[TONE_PREF])
  if (t.optIn && !hasToneConsent(prefs)) return TONES[DEFAULT_TONE]
  return t
}

// ── Возможности по тирам ──────────────────────────────────────────────────────
// Расход считается деньгами, а не штуками — таблица бюджетов и цен живёт в
// aiBudget.js. Здесь только то, что деньгами не измеряется: память и пуши.
export const TIER_FEATURES = Object.freeze({
  [TIER.FREE]:       { memory: false, push: false, photo: true, digest: false },
  [TIER.AI]:         { memory: false, push: true,  photo: true, digest: true },
  [TIER.AI_PLUS]:    { memory: true,  push: true,  photo: true, digest: true },
  [TIER.AI_PREMIUM]: { memory: true,  push: true,  photo: true, digest: true },
})

// Нормализованный тариф: 'FREE' | 'AI' | 'AI_PLUS', с учётом того, что
// подписка Stripe считается действующей только в живых статусах. Единая
// точка, чтобы featuresFor и текст про лимит тарифа не разошлись в том,
// что считают активным.
export function normalizedTier(sub) {
  const tier = sub?.tier || TIER.FREE
  const active = tier !== TIER.FREE && ['active', 'trialing', 'past_due'].includes(sub?.status)
  return active ? tier : TIER.FREE
}

export function featuresFor(sub) {
  return TIER_FEATURES[normalizedTier(sub)]
}

// Что сказать про лимит истории, если он стал причиной «не вижу данные».
// Числа берём из aiContext.HISTORY_DAYS — той же таблицы, что реально режет
// историю в контексте, поэтому объяснение не может разойтись с фактом.
function tierLimitNote(tier) {
  const days = HISTORY_DAYS[tier] ?? HISTORY_DAYS[TIER.FREE]
  const unlimited = MONTHLY_BUDGET[tier] === null // нет дневного потолка запросов
  const plural = (n) => (n % 10 === 1 && n % 100 !== 11 ? 'день' : (n % 10 >= 2 && n % 10 <= 4 && (n % 100 < 10 || n % 100 >= 20) ? 'дня' : 'дней'))

  // Название тарифа, как его видит человек на экране тарифов. FREE не продаётся,
  // поэтому для него — «бесплатный», для остальных — торговое имя из PLANS.
  const planName = PLANS.find((p) => p.tier === tier)?.name
  const shown = tier === TIER.FREE ? 'бесплатный' : (planName || tier)

  // Следующий тариф вверх — чтобы объяснить, что даёт апгрейд, без ручного
  // перечисления. На самом верхнем тарифе апгрейда нет.
  const next = PLANS.filter((p) => TIER_RANK[p.tier] > TIER_RANK[tier])
    .sort((a, b) => TIER_RANK[a.tier] - TIER_RANK[b.tier])[0]
  const nextDays = next ? (HISTORY_DAYS[next.tier] ?? days) : null

  const budgetLine = unlimited
    ? 'На сообщения нет дневного лимита.'
    : 'Сообщений в день ограниченное число (дневной лимит по расходу).'

  const upsell = next
    ? `Если он спрашивает про даты за пределами этого окна — объясни коротко, одной фразой: сколько дней видишь сейчас и что на тарифе ${next.name} история за ${nextDays} ${plural(nextDays)}${MONTHLY_BUDGET[next.tier] === null ? ' и без лимита на сообщения' : ''}. Не уговаривай и не повторяй это в каждом ответе — только когда лимит истории реально стал причиной, почему не можешь ответить.`
    : `Если он спрашивает про даты за пределами этого окна — просто скажи, сколько дней видишь, без предложений апгрейда: это уже максимальный тариф.`

  return `ТАРИФ
У этого человека тариф ${shown}: ты видишь последние ${days} ${plural(days)} дневника. ${budgetLine}
${upsell}
Про сам тариф вспоминай, только когда лимит истории реально мешает ответу.`
}

