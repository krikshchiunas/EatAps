// ── Сборка ───────────────────────────────────────────────────────────────────
// ctx: { profile, targets, today, history, prefs, memory, tone, sub, task }
// Блок голоса. Собирается дважды: развёрнуто в начало промпта и одной строкой
// в самый конец. Повтор в конце — не избыточность: последнее указание модель
// держит лучше всего, а между ними лежат три тысячи символов механики,
// которые сами по себе звучат нейтрально и размывают характер.
function voiceBlock(tone) {
  const examples = tone.examples.map((e) => `— ${e}`).join('\n')
  return `КАК ТЫ ГОВОРИШЬ
Это главное в твоих ответах. Характер важнее гладкости: человек сам выбрал, каким
тоном с ним разговаривать, и ждёт именно его. Нейтрально-вежливый ответ там, где
выбран характерный голос, — это невыполненная просьба.

${tone.persona}

Вот как звучат твои реплики — держи эту интонацию во всех ответах:
${examples}`
}

export function buildSystemPrompt(ctx = {}) {
  const tone = toneById(ctx.tone)
  const tier = normalizedTier(ctx.sub)
  const features = TIER_FEATURES[tier]

  const parts = [IDENTITY, `\n${voiceBlock(tone)}`, `\n${CORE}`, `\n${tierLimitNote(tier)}`]

  if (!features.memory) {
    parts.push(`\nПАМЯТЬ
Долгой памяти у этого тарифа нет: ты помнишь только текущий диалог.
Не ссылайся на прошлые разговоры и не обещай что-то запомнить. Поле "memory" всегда null.`)
  } else {
    parts.push(`\nПАМЯТЬ
У пользователя AI+: ты помнишь факты о нём между сессиями. Они даны в блоке ПАМЯТЬ ниже — учитывай их всегда.
Новый устойчивый факт клади в поле "memory" (одно короткое предложение). Медицинские детали не сохраняй.`)
  }

  parts.push(`\n${OUTPUT_CONTRACT}`)
  // Последнее, что читает модель, — про голос. Рядом с форматом ответа, чтобы
  // JSON-контракт не увёл её обратно в нейтральный «служебный» регистр.
  parts.push(`\nГОЛОС — ГЛАВНОЕ\n${tone.reminder}\nЭто относится к полю "reply": именно оно попадает человеку на экран.`)
  return parts.join('\n')
}

// Контекст пользователя отдельным сообщением: так его дешевле кэшировать
// и легче резать по тиру (история 7 дней против 30).
export function buildUserContext(ctx = {}) {
  const { profile, targets, today, history, prefs, memory } = ctx
  const block = (title, body) => (body ? `## ${title}\n${body}\n` : '')
  return [
    block('ПРОФИЛЬ И ЦЕЛИ', profile && JSON.stringify({ ...profile, targets })),
    block('СЕГОДНЯ', today && JSON.stringify(today)),
    block('ИСТОРИЯ', history && JSON.stringify(history)),
    block('ОГРАНИЧЕНИЯ И ПРЕДПОЧТЕНИЯ', prefs && JSON.stringify(prefs)),
    block('ПАМЯТЬ', Array.isArray(memory) && memory.length ? memory.map((m) => `- ${m}`).join('\n') : ''),
  ].filter(Boolean).join('\n')
}
