function expandQuery(q) {
  const terms = new Set([q])
  const words = q.split(/\s+/).filter((w) => w.length >= 3)
  for (const g of SYNONYMS) {
    const hit = g.some((w) => words.some((x) => x === w || x.startsWith(w) || w.startsWith(x)))
    if (hit) g.forEach((w) => terms.add(w))
  }
  return [...terms]
}

function wordPrefixMatch(text, terms) {
  const words = text.split(/[\s\-()·,/.]+/).filter(Boolean)
  return terms.some((term) => words.some((w) => w.startsWith(term)))
}

export function searchLocal(query) {
  const q = norm(query)
  if (!q) return FOODS
  const syn = expandQuery(q).filter((t) => t !== q)
  const items = FOODS.map((f) => ({ f, text: norm(f.name + ' ' + (f.alias || '')) }))
  const prefix = items.filter(({ text }) => wordPrefixMatch(text, [q, ...syn]))
  if (prefix.length > 0) return prefix.map((x) => x.f)
  return items.filter(({ text }) => text.includes(q)).map((x) => x.f)
}

