export function getPortions(food) {
  if (!food) return []
  const isDrink = food.unit === 'мл' || food.cat === 'drink'
  const catKey = isDrink ? 'drink' : DISH_CATS.has(food.cat) ? 'dish' : food.cat
  const spec = PORTIONS_BY_NAME[food.name] || []
  const cat = PORTIONS_BY_CAT[catKey] || PORTIONS_BY_CAT._default
  const list = spec.length >= 3 ? spec : [...spec, ...cat]
  const seen = new Set()
  const out = []
  for (const [label, grams] of list) {
    if (seen.has(label)) continue
    seen.add(label)
    out.push({ label, grams })
    if (out.length >= 6) break
  }
  return out
}

export function searchIngredients(query) {
  const q = norm(query)
  if (!q) return CONSTRUCTOR_ING
  const syn = expandQuery(q).filter((t) => t !== q)
  const items = CONSTRUCTOR_ING.map((i) => ({ i, text: norm(i.name) }))
  const prefix = items.filter(({ text }) => wordPrefixMatch(text, [q, ...syn]))
  if (prefix.length > 0) return prefix.map((x) => x.i)
  return items.filter(({ text }) => text.includes(q)).map((x) => x.i)
}

export async function searchOpenFoodFacts(query, signal) {
  const url =
    'https://ru.openfoodfacts.org/cgi/search.pl?search_terms=' +
    encodeURIComponent(query) +
    '&search_simple=1&action=process&json=1&page_size=25' +
    '&fields=product_name,product_name_ru,brands,nutriments'
  const res = await fetch(url, { signal })
  if (!res.ok) throw new Error('off_http_' + res.status)
  const data = await res.json()
  const seen = new Set()
  return (data.products || [])
    .map((p) => {
      const n = p.nutriments || {}
      let kcal = n['energy-kcal_100g']
      if (kcal == null && n['energy_100g'] != null) kcal = n['energy_100g'] / 4.184
      const name = p.product_name_ru || p.product_name
      if (kcal == null || !name || !name.trim()) return null
      const brand = p.brands ? p.brands.split(',')[0].trim() : ''
      const label = brand && !name.toLowerCase().includes(brand.toLowerCase()) ? `${name} · ${brand}` : name
      const key = label.toLowerCase()
      if (seen.has(key)) return null
      seen.add(key)
      return {
        name: label,
        kcal: Math.round(kcal),
        protein: +(+(n.proteins_100g || 0)).toFixed(1),
        carbs: +(+(n.carbohydrates_100g || 0)).toFixed(1),
        fat: +(+(n.fat_100g || 0)).toFixed(1),
        emoji: '🛒',
        source: 'off',
      }
    })
    .filter((f) => f && f.kcal > 0 && f.kcal < 1000)
    .slice(0, 20)
}
