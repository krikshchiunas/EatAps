// ── Поиск ────────────────────────────────────────────────────────────────────
// Тот же механизм, что у продуктов: нормализация, синонимы, опечатки. Человек
// ищет «ашвагандха» и «ashwagandha», «д3» и «витамин д» — и должен находить.
const searchText = (s) => normalizeQuery(`${s.name} ${s.alias}`)
const searchName = (s) => normalizeQuery(s.name)

// Что люди спрашивают чаще всего. Надбавка работает ТОЛЬКО внутри тира
// релевантности (см. MEMORY_BOOST_MAX в fuzzy.js) и не может перетащить
// нерелевантное наверх: она лишь решает, кто первым среди одинаково подходящих.
// Без неё на запрос «креатин» первым выпадал «Креатин HCL» — просто потому, что
// его название короче, — хотя берут почти всегда моногидрат.
const POPULAR = new Set([
  'multi-basic', 'vitd-2000', 'omega3', 'mg-citrate', 'creatine', 'whey',
  'vitc-500', 'zn-25', 'b-complex', 'melatonin-3', 'collagen', 'probiotic-10',
  'b12', 'fe-25', 'ashwagandha', 'coq10', 'ca-d3', 'iodine',
])

export function searchSupplements(query) {
  const q = normalizeQuery(query)
  if (!q) return SUPPLEMENTS
  return rankedSearch(SUPPLEMENTS, q.split(' ').filter(Boolean), {
    toText: searchText,
    toName: searchName,
    minResults: 1,
    boost: (s) => (POPULAR.has(s.id) ? 1 : 0),
  })
}

// Подборка для пустого поиска: с чего человек чаще всего начинает.
export const POPULAR_SUPPLEMENTS = SUPPLEMENTS.filter((s) => POPULAR.has(s.id))

// ── Расчёт принятой дозы ─────────────────────────────────────────────────────
// Состав в каталоге дан на ОДНУ единицу. Здесь он умножается на количество и
// становится снимком, который уезжает в дневник. Снимок, а не ссылка на
// каталог: если завтра мы уточним состав мультивитаминов, вчерашняя запись
// человека не должна задним числом измениться — ровно так же снимками
// хранятся съеденные продукты.
export function scaleProvides(provides, dose) {
  const k = Number(dose)
  if (!Number.isFinite(k) || k <= 0) return {}
  const out = {}
  for (const key in provides) {
    const v = provides[key] * k
    // Округляем до трёх значащих разрядов дробной части: 0.001 мкг — это шум,
    // а вот 0.125 мкг витамина D из одной капли терять нельзя.
    if (v > 0) out[key] = Math.round(v * 1000) / 1000
  }
  return out
}

// Запись для дневника. Возвращает готовый объект без id и метки времени —
// их проставит стор, как и для продуктов.
export function makeSuppEntry(supp, dose = null) {
  if (!supp?.name) return null
  const amount = Number(dose ?? supp.defaultDose ?? 1)
  if (!Number.isFinite(amount) || amount <= 0) return null
  return {
    suppId: supp.id || null,
    name: supp.name,
    emoji: supp.emoji || '💊',
    unit: supp.unit || 'шт',
    dose: Math.round(amount * 100) / 100,
    provides: scaleProvides(supp.provides || {}, amount),
  }
}

// ── Свой препарат ────────────────────────────────────────────────────────────
// Каталог не может содержать всё: у человека может быть аптечная банка с
// нестандартным составом или добавка, которой у нас нет. Поэтому он может
// собрать свою — и она встаёт в общий счёт наравне с каталожными.
//
// Проверяем то, без чего запись бессмысленна: имя и хотя бы одно вещество из
// справочника с положительным количеством. Чужие ключи молча выбрасываем —
// хранить в состоянии то, что приложение не умеет показать, незачем.
export function makeCustomSupplement({ name, emoji, unit, dose, provides }) {
  const clean = String(name || '').trim()
  if (!clean) return null
  const out = {}
  for (const key in provides || {}) {
    if (!MICRO_BY_KEY[key]) continue
    const n = Number(provides[key])
    if (Number.isFinite(n) && n > 0) out[key] = Math.round(n * 1000) / 1000
  }
  if (!Object.keys(out).length) return null
  const amount = Number(dose)
  return {
    id: null,
    name: clean.slice(0, 60),
    emoji: emoji || '💊',
    group: 'custom',
    unit: unit || 'шт',
    provides: out,
    defaultDose: Number.isFinite(amount) && amount > 0 ? amount : 1,
    note: '',
    alias: '',
    warn: '',
  }
}

// Название дозы: «2 капсулы», «5 г», «1 порция». Склонение по-русски —
// единственное, что тут можно сделать неправильно и увидеть в дневнике
// «2 капсула».
const FORMS = {
  'капсула': ['капсула', 'капсулы', 'капсул'],
  'таблетка': ['таблетка', 'таблетки', 'таблеток'],
  'порция': ['порция', 'порции', 'порций'],
  'пастилка': ['пастилка', 'пастилки', 'пастилок'],
  'капля': ['капля', 'капли', 'капель'],
  'саше': ['саше', 'саше', 'саше'],
  'шт': ['шт', 'шт', 'шт'],
  'мерная ложка': ['мерная ложка', 'мерные ложки', 'мерных ложек'],
  'ч. ложка': ['ч. ложка', 'ч. ложки', 'ч. ложек'],
  'ст. ложка': ['ст. ложка', 'ст. ложки', 'ст. ложек'],
}

export function doseLabel(dose, unit) {
  const n = Number(dose)
  if (!Number.isFinite(n)) return ''
  const text = (Math.round(n * 100) / 100).toString().replace('.', ',')
  const forms = FORMS[unit]
  if (!forms) return `${text} ${unit || ''}`.trim()
  if (!Number.isInteger(n)) return `${text} ${forms[1]}`
  const mod10 = n % 10
  const mod100 = n % 100
  const form = mod10 === 1 && mod100 !== 11 ? forms[0]
    : mod10 >= 2 && mod10 <= 4 && (mod100 < 10 || mod100 >= 20) ? forms[1]
      : forms[2]
  return `${n} ${form}`
}

// Сумма по добавкам дня. Формат тот же, что у sumFoodMicros, — их складывает
// microSummary.js, и расходиться они не должны.
export function sumSuppMicros(entries = []) {
  const values = {}
  for (const e of entries || []) {
    for (const key in e?.provides || {}) {
      const v = Number(e.provides[key])
      if (Number.isFinite(v) && v > 0) values[key] = (values[key] || 0) + v
    }
  }
  return { values, count: (entries || []).length }
}
