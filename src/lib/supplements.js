// Каталог добавок: банки, которые реально стоят у людей на полке.
//
// Одна запись — один типовой продукт с типовой дозировкой на этикетке. Состав
// (`provides`) указан НА ОДНУ ЕДИНИЦУ приёма: одну капсулу, одну таблетку,
// одну мерную ложку, один грамм. Человек выбирает, сколько единиц принял, и
// содержимое умножается.
//
// ── Почему состав хранится в базовых единицах микронутриентов ───────────────
// На этикетках пишут как угодно: витамин D в международных единицах, B12 в
// микрограммах, магний в миллиграммах, креатин в граммах. Если тащить эту
// пестроту дальше в приложение, складывать еду с добавками станет невозможно —
// одно и то же вещество окажется в разных величинах. Поэтому пересчёт делается
// ЗДЕСЬ, один раз, при заполнении каталога:
//
//   витамин D: 1 мкг = 40 МЕ   →  2000 МЕ = 50 мкг
//   витамин A: 1 МЕ ретинола ≈ 0.3 мкг RAE  →  5000 МЕ = 1500 мкг
//   витамин E: 1 МЕ (d-альфа) ≈ 0.67 мг     →  400 МЕ ≈ 268 мг
//
// В поле `note` при этом остаётся то, что написано на банке, — человек должен
// узнать свою добавку по этикетке, а не по нашему пересчёту.
//
// ── Чего здесь нет ──────────────────────────────────────────────────────────
// Ни гормонов, ни рецептурных препаратов, ни жиросжигателей на эфедрине и
// йохимбине. Это дневник питания, а не аптека: показывать такое рядом с
// «выпил — отметил» значит подталкивать к приёму.
// ─────────────────────────────────────────────────────────────────────────────

