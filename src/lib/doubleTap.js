// Двойной тап / двойной клик по элементу списка — ЧИСТАЯ часть.
//
// Вынесено из ChatView по той же причине, что relationship.js и
// notificationModel.js: внутри компонента эту логику нельзя проверить ничем,
// кроме пальца на реальном телефоне, а ошибиться в ней легко — она про
// последовательности событий, а не про разметку.
//
// Задача не сводится к «посчитать два тапа». На телефоне к нам приходят ДВА
// независимых сигнала об одном и том же жесте:
//
//   1. пара touchstart/touchend, которую мы считаем сами;
//   2. dblclick, который браузер синтезирует из той же пары тапов, потому что
//      двойной тап-зум отключён вьюпортом (user-scalable=no).
//
// Если обработать оба, реакция ставится и тут же снимается: пользователь видит
// вспышку морковки и пустой пузырь. Поэтому оба пути идут через один объект,
// и после засчитанного двойного ТАПА следующий dblclick по тому же элементу
// глушится один раз. Настоящий двойной клик мышью тач-событий не порождает,
// глушитель для него всегда пуст, и на десктопе жест работает как работал.

// Насколько палец может уехать, и тап всё ещё остаётся тапом. Двойной тап
// люди делают быстро и неточно: без допуска вторая метка не засчитывается, и
// реакция «не ставится» через раз.
export const TAP_SLOP = 14

// Окно двойного тапа. Больше — и обычные два отдельных нажатия начнут
// склеиваться в жест; меньше — человек не успевает.
export const DOUBLE_TAP_MS = 320

// Сколько ждём синтезированный dblclick после засчитанного двойного тапа.
// Браузер шлёт его сразу за вторым touchend, так что окно с запасом.
const SYNTHETIC_DBLCLICK_MS = 700

export function createDoubleTap({
  slop = TAP_SLOP,
  windowMs = DOUBLE_TAP_MS,
  now = Date.now,
} = {}) {
  let lastTap = { id: null, time: 0 }
  let swallow = null

  return {
    // Конец касания. Возвращает true, если это была вторая метка двойного
    // тапа и вызывающему пора действовать.
    //
    //   id          — что нажали (у нас data-mid сообщения)
    //   drift       — максимальный отход пальца от точки касания за жест
    //   interactive — попали в ссылку/кнопку: у них своё поведение
    //   swipe       — жест уже опознан как свайп, тапом он быть не может
    touchEnd({ id, drift = 0, interactive = false, swipe = false } = {}) {
      if (id == null || interactive || swipe || drift > slop) return false
      const t = now()
      if (lastTap.id === id && t - lastTap.time < windowMs) {
        lastTap = { id: null, time: 0 }
        // Взводим глушитель: dblclick по этому же элементу сейчас прилетит
        // как эхо только что обработанного жеста.
        swallow = { id, time: t }
        return true
      }
      lastTap = { id, time: t }
      return false
    },

    // Двойной клик. Возвращает true для настоящей мыши и false для эха с тача.
    dblClick({ id, interactive = false } = {}) {
      if (id == null || interactive) return false
      if (swallow && swallow.id === id && now() - swallow.time < SYNTHETIC_DBLCLICK_MS) {
        swallow = null
        return false
      }
      return true
    },
  }
}
