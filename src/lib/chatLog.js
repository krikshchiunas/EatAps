// Лента сообщений чата — ЧИСТАЯ часть: как страницы истории, реальное время и
// собственные ещё не отправленные сообщения складываются в один список.
//
// Без зависимостей и без импорта supabase.js — по той же причине, что у
// relationship.js: тот читает import.meta.env при импорте и падает под голым
// `node --test`.
//
// ЗАЧЕМ ЭТО ОТДЕЛЬНЫМ МОДУЛЕМ. В ChatView история приезжала так:
//
//     const rows = await listMessagesWith(...)
//     setMessages(rows)                    // ← ПЕРЕЗАПИСЬ
//
// а подписка на реальное время создавалась рядом, синхронно, и добавляла
// пришедшее в тот же список. Порядок этих двух событий ничем не задан.
// Если сообщение прилетало, пока история ещё летела, происходило вот что:
// обработчик добавлял его в пустой список, а через мгновение ответ истории
// затирал список целиком — вместе с этим сообщением. Оно пропадало до
// следующего открытия чата. Классическая гонка «загрузка против подписки»,
// и лечится она ровно одним способом: не перезаписывать, а СЛИВАТЬ.
//
// Слияние идемпотентно: один и тот же список, слитый дважды, не меняется.
// Поэтому повторная загрузка страницы, дубль realtime-события и переподписка
// после разрыва связи не создают ни дублей, ни пропусков.

import { newId } from './uuid.js'

// Ключ сортировки: время, затем id. Второй нужен для сообщений, у которых
// совпала метка времени, — без него порядок был бы недетерминированным и
// список подрагивал бы при каждой перерисовке.
function orderKey(m) {
  return [Date.parse(m?.created_at) || 0, String(m?.id || '')]
}

function compare(a, b) {
  const [ta, ia] = orderKey(a)
  const [tb, ib] = orderKey(b)
  if (ta !== tb) return ta - tb
  return ia < ib ? -1 : ia > ib ? 1 : 0
}

export function isTempId(id) {
  return String(id || '').startsWith('temp-')
}

// Слить страницы истории, realtime-события и локальные черновики в один
// упорядоченный список без дублей.
//
// Приоритет полей у более ПОЗДНЕГО источника: свежее событие (прочтение,
// реакция) должно перекрывать то, что лежало в истории, а не наоборот.
// Локальные поля черновика (status, _payload, _clientId) при этом
// сохраняются: серверная строка про них не знает, а интерфейсу они нужны,
// пока сообщение не подтверждено.
export function mergeMessages(...sources) {
  const byId = new Map()
  for (const list of sources) {
    for (const m of list || []) {
      if (!m || m.id == null) continue
      const key = String(m.id)
      const prev = byId.get(key)
      byId.set(key, prev ? { ...prev, ...m } : m)
    }
  }
  return [...byId.values()].sort(compare)
}

// Подтверждение отправки: временное сообщение заменяется серверной строкой.
//
// Отдельная функция, а не «удалить по tempId и добавить»: между этими двумя
// действиями сообщение на мгновение исчезает из списка, и лента дёргается.
// Здесь замена происходит на месте, а если серверная строка УЖЕ приехала по
// realtime (так бывает при медленном ответе на insert), временная просто
// исчезает и дубля не возникает.
export function settleMessage(list, tempId, row) {
  if (!row) return list || []
  const withoutTemp = (list || []).filter((m) => String(m.id) !== String(tempId))
  return mergeMessages(withoutTemp, [{ ...row, status: undefined, _payload: undefined }])
}

// Пометить неотправленное сообщение сбойным, сохранив всё нужное для повтора.
export function failMessage(list, tempId, payload) {
  return (list || []).map((m) => (
    String(m.id) === String(tempId) ? { ...m, status: 'failed', _payload: payload } : m
  ))
}

// Ключ идемпотентности живёт на самом сообщении и НЕ меняется при повторе:
// в этом весь смысл. Сервер, увидев знакомый ключ, вернёт уже сохранённую
// строку вместо второй такой же — то есть «отправил, сеть отвалилась,
// повторил» перестаёт создавать два одинаковых сообщения в переписке.
//
// Берём общий генератор проекта, но с проверкой формы. У newId есть последний
// рубеж на случай браузера вовсе без криптографии — «время + два случайных
// хвоста», и это НЕ UUID. Для ключа записи в дневнике такой строки достаточно,
// а здесь нет: колонка messages.client_id имеет тип uuid, и вставка с чем-то
// другим не пройдёт вовсе. Поэтому форму проверяем и при несовпадении
// собираем UUID сами.
const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i

export function newClientId() {
  const id = newId()
  if (UUID_RE.test(id)) return id

  const hex = '0123456789abcdef'
  let out = ''
  for (let i = 0; i < 36; i++) {
    if (i === 8 || i === 13 || i === 18 || i === 23) out += '-'
    else if (i === 14) out += '4'
    else if (i === 19) out += hex[(Math.random() * 4 | 0) + 8]
    else out += hex[Math.random() * 16 | 0]
  }
  return out
}
