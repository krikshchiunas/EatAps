// Нормализация названий продуктов для группировки и сравнения.
// Живёт отдельным модулем, потому что нужна и статистике, и корреляциям, и
// библиотеке избранного — а импортировать их друг из друга значило бы завести
// циклическую зависимость.
export function normalizeName(s) {
  return (s || '').toLowerCase().replace(/ё/g, 'е').replace(/\s+/g, ' ').trim()
}
