export const SYNONYM_WEIGHT = 0.75

// Слова запроса → дополнительные варианты запроса из групп.
export function expandSynonyms(folded) {
  const words = folded.split(' ').filter((w) => w.length >= 3)
  if (!words.length) return []
  const out = new Set()
  for (const g of SYNONYM_GROUPS) {
    const hit = g.some((w) => words.some((x) => x === w || x.startsWith(w) || w.startsWith(x)))
    if (hit) for (const w of g) if (w !== folded) out.add(w)
  }
  return [...out]
}
